// Compiles the 3D avatar scene (app/components/avatar3d/scene.ts) to plain JavaScript in
// public/avatar-runtime.js. The avatar studio inlines that file into the single-file
// avatar people download, so the download runs the exact same code as the site.
import { readFileSync, writeFileSync } from 'node:fs'
import ts from 'typescript'

const src = readFileSync(new URL('../app/components/avatar3d/scene.ts', import.meta.url), 'utf8')
const { outputText } = ts.transpileModule(src, {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, removeComments: false },
})
const three = JSON.parse(readFileSync(new URL('../node_modules/three/package.json', import.meta.url), 'utf8'))
const out = new URL('../public/avatar-runtime.js', import.meta.url)
writeFileSync(out, `// Generated by scripts/build-avatar-runtime.mjs — do not edit.\n// three-version: ${three.version}\n${outputText}`)
console.log('avatar runtime written to public/avatar-runtime.js')
